# The generator of the Didit Ruby SDK's generated layer (docs/DESIGN.md section 5).
# It reads only openapi/ and writes lib/didit/resources*, lib/didit/types*, the
# matching RBS signatures under sig/ and one test per operation under spec/generated/.
module DiditCodegen
  # The OpenAPI documents or the overlay cannot be turned into the SDK.
  class Error < StandardError; end

  HEADER = "# Code generated by codegen from openapi/*.json. DO NOT EDIT."
  RBS_HEADER = HEADER
end

